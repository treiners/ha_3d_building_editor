// Generates docs/FILE-FORMAT.md, the description of the floor-plan file for people who read it (for example the 3D visualisation).
// Everything that is a number or a list in the code (default values, entity types, area kinds, the version the editor writes) is
// read from the code itself, so the document cannot drift: test/file-format-doc.test.ts fails when docs/FILE-FORMAT.md differs from
// this output. Regenerate with `npm run docs:format` (after `npm run build`). The prose is written here; keep it short and exact.
import { migrate } from './core.js';
import { fillDefaults } from './defaults.js';
import { entityCatalog } from './entities.js';
import { areaKinds } from './areas.js';
import { objectCatalog } from './objects.js';

const table = (head: string[], rows: string[][]): string[] => [
  '| ' + head.join(' | ') + ' |',
  '|' + head.map(() => '---').join('|') + '|',
  ...rows.map((r) => '| ' + r.join(' | ') + ' |'),
  '',
];
const num = (v: unknown): string => (typeof v === 'number' ? String(v) : '');

export function fileFormatMarkdown(): string {
  // Defaults, read by running the real code on a tiny graph with one connector of each kind.
  const tiny = {
    schemaVersion: '2.14', id: 'x', name: 'x',
    rooms: [{
      id: 'a', name: 'A', type: 'room', sizeCategory: 'medium', layout: { x: 0, y: 0, width: 4, height: 3 },
      connectors: [
        { id: 'a-door', roomId: 'a', side: 'right', type: 'door', doorType: 'hinged' },
        { id: 'a-open', roomId: 'a', side: 'top', type: 'open-passage' },
        { id: 'a-window', roomId: 'a', side: 'bottom', type: 'window' },
      ],
    }],
    relationships: [], wallAlignments: [],
  };
  const filled = fillDefaults(tiny);
  const [door, open, win] = filled.rooms[0].connectors;
  const b = filled.buildingDefaults;
  const writtenVersion = migrate(tiny).schemaVersion;

  const kinds = Object.entries(areaKinds()).map(([k, v]) => [`\`${k}\``, String(v.label), String(v.shape), `${v.size[0]} x ${v.size[1]}`]);
  const types = Object.entries(entityCatalog()).map(([k, v]) => [
    `\`${k}\``, String(v.label),
    v.anchor === 'connector' ? `connector (${(v.connectorTypes || []).join(', ')})` : 'room or area',
    num(v.height), v.directional ? `${v.facingDegrees} / ${v.fieldOfViewDegrees} / ${v.range}` : '',
    v.outdoor ? 'yes' : '', v.onObject ? 'yes' : '',
  ]);

  const objectRows = Object.entries(objectCatalog()).map(([k, v]) => [`\`${k}\``, v.label, v.category, `${v.width} x ${v.depth} x ${v.height}`, num(v.elevation), num(v.clearance)]);

  const L: string[] = [];
  L.push(
    '# Floor-plan file format',
    '',
    '_Generated by `npm run docs:format` from `src/file-format-doc.ts` (do not edit by hand; a test compares it with the code)._',
    '',
    'One JSON file describes one house: rooms with their connectors, how rooms are connected, where everything is, and the things that',
    'are added on top (floors, stairs, outside areas, sensors and other entities). The editor reads older files and writes every default',
    'explicitly, so a saved file is complete.',
    '',
    '## Conventions',
    '',
    '- Lengths are **metres**. **x points right, y points down** (screen orientation). All floors share one coordinate frame.',
    '- On save the origin is moved to the top-left corner of the house and coordinates are rounded.',
    '- Angles are **degrees**. `facingDegrees` is clockwise from up (north on the plan): 0 = up, 90 = right. `northDegrees` is how far the plan\'s up is turned away from true north.',
    '- Ids are short slugs, unique within their kind (rooms, connectors, relationships, floors, stairs, areas, entities).',
    '- Every field after the original core is optional: a reader may ignore fields it does not know.',
    '',
    '## Versions',
    '',
    '- `2.14`: the core (`rooms`, `relationships`, `wallAlignments`, `joints`, `buildingDefaults`).',
    '- `3.0`: the same core plus the optional parts `floors`, `stairs`, `areas`, `entityPlacements`, `entitySettings`, `northDegrees`. Nothing of the core changed.',
    '- Objects (`objects`, `objectTypes`) and the entity anchor `objectId` are further optional parts of the same format (editor 3.1); a reader that does not know them can ignore them.',
    `- The editor currently writes \`schemaVersion: "${writtenVersion}"\` and reads both.`,
    '',
    '## Top level',
    '',
    ...table(['Field', 'Meaning'], [
      ['`schemaVersion`', 'Format version, see above.'],
      ['`id`, `name`', 'Identifier and display name of the house.'],
      ['`rooms`', 'List of rooms (below). A room named `Outside` is a normal room that the editor hides when drawing.'],
      ['`relationships`', 'Which two connectors form one shared opening (door, open passage, window pair).'],
      ['`wallAlignments`', 'Groups of rooms whose walls on one side are kept in line: `{ id, side, roomIds[] }`.'],
      ['`joints`', 'Optional. `{ relationshipId, state: "attached" or "detached" }`: a wall the user detached on purpose. Absent = everything attached.'],
      ['`buildingDefaults`', `Wall and floor values: \`wallThickness\` (${b.wallThickness}), \`wallHeight\` (${b.wallHeight}), \`floorThickness\` (${b.floorThickness}) metres; the numbers in brackets are the defaults.`],
      ['`floors`, `stairs`, `areas`', 'Optional, below.'],
      ['`entityPlacements`, `entitySettings`', 'Optional, below.'],
      ['`objects`, `objectTypes`', 'Optional, below.'],
      ['`northDegrees`', 'Optional. Rotation of the plan against true north, degrees.'],
    ]),
    '## Rooms',
    '',
    '`{ id, name, type, sizeCategory, connectors[], layout, floor? }`',
    '',
    '- `sizeCategory`: `small` (3 x 2 m), `medium` (4 x 3), `large` (6 x 4): the default size when a room has no `layout` yet.',
    '- `layout`: `{ x, y, width, height }`, top-left corner and size. Optional lock flags: `positionLocked` (corner fixed), `sizeLocked` (size fixed); old files use `locked: true` for both.',
    '- `floor`: id of the floor the room is on; absent = the first floor.',
    '',
    '## Connectors',
    '',
    '`{ id, roomId, side, type, offset, width, doorType?, door?, window? }`, listed in the room they belong to.',
    '',
    '- `side`: `top`, `right`, `bottom`, `left` (the wall of the room). Only opposite sides can share a wall.',
    '- `offset`: metres from the start of the wall (left end for top / bottom walls, top end for left / right walls), at least 0.05 m from either end. `position` (0..1) is the legacy form of the same value and may still appear in old files.',
    '- `type`: `door`, `open-passage` or `window`.',
    `- \`width\` default by type: door ${door.width} m, open passage ${open.width} m, window ${win.width} m.`,
    '- `doorType`: values starting with `hinged` are hinged doors. A hinged door has `door: { hinge, swing, openAngle }`: `hinge` is `left` or `right`, `swing` is `inward` or `outward`, `openAngle` in degrees.',
    `  Defaults: hinge \`${door.door.hinge}\`, swing \`${door.door.swing}\`, openAngle ${door.door.openAngle}. The partner connector of a pair is the mirror image.`,
    `- A window has \`window: { type, sillHeight, headHeight, frameDepth }\`, defaults \`${win.window.type}\`, ${win.window.sillHeight}, ${win.window.headHeight}, ${win.window.frameDepth} (metres above the floor / metres).`,
    '',
    '## Relationships',
    '',
    '`{ id, connectorA, connectorB, importance }`: two connectors on opposite walls of two rooms that touch. The opening sits where the two connectors are (they are within 0.2 m of each other when the pair is consistent).',
    '',
    '- `importance`: `required` relationships weigh most when the mapper places rooms (1 against 0.4); any other value counts less.',
    '',
    '## Floors and stairs',
    '',
    '- `floors`: `[{ id, name, height?, elevation? }]`. `height` = floor to ceiling, `elevation` = height of the floor surface above the lowest floor; both are filled on save.',
    '- `stairs`: `[{ id, name?, lower, upper, x, y, length, width, direction, fromRoom?, toRoom? }]`. `lower` / `upper` are floor ids of two floors directly above each other. `x, y` is the top-left corner of the stair rectangle, `length` runs along `direction` (`right`, `left`, `up`, `down` = the way the stair climbs on the plan), `width` across it.',
    '  The landing bar is at the start of the stair on the lower floor and at the end on the upper floor. `fromRoom` / `toRoom` are derived on save: the room under the middle of that bar (null = none).',
    '',
    '## Areas (outside)',
    '',
    '`areas`: `[{ id, name, kind, shape, layout }]`, a labelled footprint that is not part of the room graph. `shape` is `rect` or `ellipse`, `layout` as for rooms.',
    '',
    ...table(['kind', 'Label', 'shape', 'default size (m)'], kinds),
    '## Entities',
    '',
    '`entityPlacements`: sensors, lights, contacts and so on, placed on the plan. `{ id, type, name?, haEntityId?, roomId | areaId | connectorId | objectId, side?, position?, height?, facingDegrees?, fieldOfViewDegrees?, range? }`',
    '',
    '- Exactly one anchor: `roomId`, `areaId`, `connectorId` or `objectId` (connector entities have no `position`; `side` `A` or `B` says which room of the pair). `objectId` puts the entity ON an object (see below) and only fits the types marked in the last column of the table.',
    '- `position`: `[x, y]` metres. With `entitySettings.coordinates` = `room` (default) it is measured from the top-left corner of the room or area, otherwise from the plan origin. With `objectId` it is measured from the CENTRE of the object in the object\'s own frame (x along its width, y along its depth, turned with its `facingDegrees`), so the entity follows the object; `height` then defaults to the top of the object. `entitySettings.gridStep` is the placement grid.',
    '- `height`: metres above the floor. `haEntityId`: the Home Assistant entity this placement stands for.',
    '- `facingDegrees`, `fieldOfViewDegrees` (full opening angle), `range` (metres): for directional types only.',
    '',
    ...table(['type', 'Label', 'Anchor', 'height (m)', 'facing / field of view / range', 'Outdoors', 'On objects'], types),
    '## Objects (appliances, furniture)',
    '',
    '`objects`: `[{ id, type, name?, roomId | areaId, position, facingDegrees?, width?, depth?, height?, elevation?, category? }]`: things with a footprint, such as a refrigerator or a sofa.',
    '',
    '- Exactly one host: `roomId` or `areaId`. `position`: `[x, y]` metres, the CENTRE of the footprint measured from the top-left corner of the room or area (x right, y down).',
    '- `facingDegrees`: the direction the front points to, clockwise from up (0 = up on the plan, 90 = right), the same convention as for entities. `width` runs across the front, `depth` from front to back; at facing 0 the width is along x.',
    '- `height` and `elevation` (height of the underside above the floor, for wall-mounted things) are in metres. `category` is `appliance` or `furniture`; a reader may hide furniture.',
    '- `type` is a built-in type (table below) or an `id` from `objectTypes`: `[{ id, label, category, width, depth, height, elevation?, clearance? }]`. A custom type with the id of a built-in one replaces it. `clearance` is the free space needed in front (metres).',
    '- Width, depth, height, elevation, category and name are written explicitly on save; they default to the type.',
    '- Deleting a room or area deletes its objects, and deleting an object deletes the entities on it.',
    '',
    ...table(['type', 'Label', 'category', 'width x depth x height (m)', 'elevation (m)', 'clearance (m)'], objectRows),
    '## What the editor checks before saving',
    '',
    'Errors (the file would be wrong): `duplicate-room`, `duplicate-connector`, `duplicate-relationship`, `duplicate-area`, `duplicate-object` (repeated ids), `no-layout`, `unknown-floor`, `connector-room`, `dangling-connector`, `dangling-alignment`, `stairs-floors`, `stairs-size`, `relationship-invalid`, `dangling-object`.',
    'Warnings (the file is usable): `stairs-room`, `relationship-broken` (the pair is not aligned), `entity-*` (the entity checks, for example low coverage, no door contact, no motion sensor, `outside-object` for a position beyond the footprint of its object), `area-*`, `object-*` (`unknown-type`, `outside`, `overlap`, `blocks-door`, `too-high`; only doors count for `blocks-door`, open passages are free).',
    '',
  );
  return L.join('\n');
}
